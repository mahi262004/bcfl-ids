"""Generate docs/RESULTS.md from the measured results, so no number is typed by hand."""
from __future__ import annotations

import json

from bcfl_ids.config import DEVICES, RESULTS_DIR, ROOT


def load(name: str):
    return json.loads((RESULTS_DIR / f"{name}.json").read_text())


def f(stat, digits=3) -> str:
    return "n/a" if stat is None or stat["mean"] is None else f"{stat['mean']:.{digits}f} ± {stat['std']:.{digits}f}"


def p(value, digits=2) -> str:
    return "n/a" if value is None else f"{value * 100:.{digits}f}%"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    g, audit, ex, cal = load("grid_summary"), load("data_audit"), load("explain_eval"), load("calibration")
    meta = json.loads((ROOT / "artifacts" / "demo" / "meta.json").read_text())
    cells = {(c["attack"], c["defence"]): c for c in g["cells"]}
    clean = cells[("none", "proposed")]
    out = [
        "# Measured results",
        "",
        "Generated by `experiments/write_results.py` from `artifacts/results`. Do not edit by hand.",
        "",
        "## Setup",
        "",
        f"- **Data:** N-BaIoT, all 7,062,606 rows converted, row counts checked against the published table. One federated client per device.",
        f"- **Task:** 11 classes (benign and 10 botnet attack families).",
        f"- **Split:** chronological within every source file: train 0-68%, validation 70-78%, test 80-100%, with gaps so sliding-window features cannot overlap.",
        f"- **Grid:** {g['meta']['total_runs']} runs, {g['meta']['seeds']} seeds, {g['meta']['rounds']} rounds, {g['meta']['train_fraction'] * 100:.0f}% stratified training sample, tested on all {g['meta']['test_rows']:,} held-out test rows.",
        "- **Model:** MLP 115-128-64-11, Adam, learning rate 0.003, batch 256, 1 local epoch.",
        "- **No tuning on test data:** thresholds and training settings were chosen on the validation split with seeds 101 and 102.",
        f"- **Attackers:** a random set of clients per seed. Headline metrics use honest devices only.",
        "",
        "## Detector with no attacker",
        "",
        table(["Metric", "Proposed defence"], [
            ["Attack recall", f(clean["attack_recall"], 4)],
            ["Benign recall", f(clean["benign_recall"], 4)],
            ["MCC (attack vs benign)", f(clean["mcc"], 4)],
            ["Macro F1, 11 classes", f(clean["macro_f1"])],
            ["Macro F1, look-alike families merged", f(clean["macro_f1_merged"])],
            ["Worst device, benign recall", f(clean["worst_device_benign_recall"], 4)],
        ]),
        "",
        f"The deployed model (seed {meta['seed']}, {meta['train_fraction'] * 100:.0f}% training sample) scored macro F1 {meta['test_metrics']['macro_f1']:.3f}, attack recall {p(meta['test_metrics']['attack_recall'])}, benign recall {p(meta['test_metrics']['benign_recall'])} on {meta['test_records']:,} test rows.",
        "",
        "### Per family, one seed",
        "",
        table(["Family", "Precision", "Recall", "F1", "Test rows"], [[name, f"{v['precision']:.3f}", f"{v['recall']:.3f}", f"{v['f1']:.3f}", f"{v['support']:,}"] for name, v in clean["family"].items()]),
        "",
        "### Per device, benign recall (95% interval)",
        "",
        table(["Device", "Benign recall", "Interval", "Benign test rows"], [[DEVICES[int(k)][0], p(v["benign_recall"]), f"{p(v['benign_recall_ci'][0])} to {p(v['benign_recall_ci'][1])}", f"{v['benign_test_rows']:,}"] for k, v in clean["devices"].items()]),
        "",
        "## How hard is the data?",
        "",
        table(["Baseline", "Attack vs benign accuracy", "Macro F1 (11 classes)"], [
            ["Always say attack", p(audit["always_attack"]["binary_accuracy"]), "n/a"],
            [f"One feature ({audit['best_single_feature']['feature']})", p(audit["best_single_feature"]["binary_accuracy"]), "n/a"],
            ["Decision tree, depth 3", p(audit["tree_depth3"]["binary_accuracy"]), f"{audit['tree_depth3']['macro_f1']:.3f}"],
            ["Logistic regression", p(audit["logistic_regression"]["binary_accuracy"]), f"{audit['logistic_regression']['macro_f1']:.3f}"],
            ["Random forest, pooled, chronological split", p(audit["random_forest"]["binary_accuracy"]), f"{audit['random_forest']['macro_f1']:.3f}"],
            ["Random forest, pooled, random split", p(audit["random_forest_random_split"]["binary_accuracy"]), f"{audit['random_forest_random_split']['macro_f1']:.3f}"],
        ]),
        "",
        f"Attack versus benign is close to solved by simple models. Family classification is not: the pooled random forest has recall {audit['random_forest']['family_recall']['gafgyt_tcp']:.2f} on gafgyt_tcp and {audit['random_forest']['family_recall']['gafgyt_junk']:.2f} on gafgyt_junk on the chronological split. A random split raises macro F1 from {audit['random_forest']['macro_f1']:.3f} to {audit['random_forest_random_split']['macro_f1']:.3f}, which is why this project uses the chronological split.",
        "",
        "Hold one device out of training (random forest, attack vs benign): "
        + ", ".join(f"device {k}: {p(v['binary_accuracy'])}" for k, v in audit["device_holdout"].items()) + ".",
        "",
        "## Every attack against every defence (3 of 9 clients malicious)",
        "",
    ]
    defences, attacks = g["defences"], g["attacks"]
    for metric, title in (("macro_f1", "Macro F1, 11 classes"), ("macro_f1_merged", "Macro F1, look-alike families merged"), ("attack_recall", "Attack recall"), ("benign_recall", "Benign recall")):
        out += [f"### {title}", "", table(["Attack"] + [g["defence_labels"][d] for d in defences], [[a] + [f(cells[(a, d)][metric]) if (a, d) in cells else "n/a" for d in defences] for a in attacks]), ""]
    out += ["### Targeted evasion: share of mirai_syn traffic passed as benign", "", table(["Attack"] + [g["defence_labels"][d] for d in defences], [["targeted_evasion"] + [f(cells[("targeted_evasion", d)]["target_family_evasion"]) for d in defences]]), ""]
    out += ["### Trust gate behaviour", "", table(["Attack", "Attacker updates rejected (proposed)", "Honest updates rejected (proposed)"], [[a, p(cells[(a, "proposed")]["attacker_reject_rate"]["mean"], 1), p(cells[(a, "proposed")]["false_reject_rate"]["mean"], 1)] for a in attacks if a != "none"]), ""]
    out += ["### Number of attackers", "", table(["Attack", "Attackers", "No defence, macro F1", "Proposed, macro F1"], [
        [c["attack"], c["n_attackers"], f(c["macro_f1"]), f(next(o["macro_f1"] for o in g["scaling_attackers"] if o["attack"] == c["attack"] and o["n_attackers"] == c["n_attackers"] and o["defence"] == "proposed"))]
        for c in sorted((c for c in g["scaling_attackers"] if c["defence"] == "fedavg"), key=lambda c: (c["attack"], c["n_attackers"]))
        if any(o["attack"] == c["attack"] and o["n_attackers"] == c["n_attackers"] and o["defence"] == "proposed" for o in g["scaling_attackers"])
    ]), ""]
    pct = cal["honest_cosine_percentiles"]
    rat = cal["honest_ratio_percentiles"]
    del10 = next(d for d in ex["deletion"] if d["k"] == 10)
    out += [
        "## Gate calibration (validation split)",
        "",
        f"Across {cal['honest_client_rounds']} honest client-rounds, cosine to the median ranged from {pct['0']:.3f} to {pct['100']:.3f} and the norm ratio from {rat['0']:.3f} to {rat['100']:.3f}. The chosen limits are cosine at least 0.1 and norm ratio at most 2.",
        "",
        "## Explanations",
        "",
        f"- **Baseline check:** the mean of all traffic is itself classified as {ex['baseline_check']['global_mean_predicted_as']}, so it is a poor reference. Explanations use mean benign traffic, classified as {ex['baseline_check']['benign_mean_predicted_as']}.",
        f"- **Completeness:** median relative error {p(ex['completeness']['median_relative_error'], 3)}. This confirms the integration is implemented correctly; it says nothing about faithfulness.",
        f"- **Deletion:** removing the top 10 features removes {p(del10['evidence_removed_top'], 0)} of the evidence and flips {p(del10['flipped_top'], 0)} of decisions, against {p(del10['evidence_removed_random'], 0)} and {p(del10['flipped_random'], 0)} for 10 random features.",
        f"- **Untrained-model sanity check:** rank correlation {ex['sanity_random_model_spearman']:.2f} with explanations from a randomly initialised model.",
        f"- **Stability across seeds:** rank correlations " + ", ".join(f"{v:.2f}" for v in ex["stability_across_seeds_spearman"].values()) + "; top-20 overlap " + ", ".join(p(v, 0) for v in ex["stability_top20_overlap"].values()) + ".",
        "",
        table(["Attack on the defended model", "Macro F1", "Rank correlation with clean", "Top-20 overlap"], [[k, f"{v['macro_f1']:.3f}", f"{v['spearman_to_clean']:.2f}", p(v["top20_overlap_to_clean"], 0)] for k, v in ex["under_attack"].items()]),
        "",
        "## Limits",
        "",
    ]
    out += [f"- {t}" for t in g["limits"]]
    out += [
        "",
        "## Differences from the Dissertation-I report",
        "",
        "The numbers above replace those in the Dissertation-I report (October 2026). They were produced by the code in this repository, and they differ for these reasons:",
        "",
        "- 11-class detection, where the report used binary labels.",
        "- Chronological split, where the report used a random stratified split.",
        "- Cosine limit 0.1, where the report used -0.1, chosen from a new calibration on validation data.",
        "- Norm ratio measured against the median update size, where the report used the norm of the median update. The first full run of this grid showed the report's form lets Min-Max attackers get honest updates rejected. The fix was chosen on validation data and the affected runs were repeated, but it was prompted by test results, which is a mild selection effect.",
        "- Mean benign traffic as the explanation baseline, where the report used the mean of all traffic.",
        "- Random attacker sets per seed, where the report fixed devices 4, 1 and 6.",
        "- Added attacks: scaling, targeted evasion, LIE, Min-Max, Fang, statistics poisoning. Added defences for comparison: median, Multi-Krum, and each layer separately.",
    ]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
